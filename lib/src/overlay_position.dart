/// Where the front-camera picture-in-picture overlay is placed on the
/// composited image.
enum OverlayPosition {
  /// Bottom-right corner of the back-camera image (default).
  bottomRight,

  /// Bottom-left corner of the back-camera image.
  bottomLeft,

  /// Top-right corner of the back-camera image.
  topRight,

  /// Top-left corner of the back-camera image.
  topLeft,
}
